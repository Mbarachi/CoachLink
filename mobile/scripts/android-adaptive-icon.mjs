#!/usr/bin/env node
/**
 * Replaces the Android adaptive launcher icon with vector sources.
 *
 * capacitor-assets writes the adaptive foreground and background as PNGs at the
 * *legacy* launcher sizes — 48/72/96/144/192 — but an adaptive layer is 108dp,
 * which needs 108/162/216/324/432. At xxxhdpi the launcher was therefore
 * upscaling a 192px bitmap to 432px, so both the mark and the flat background
 * came out soft. Its XML then insets each layer by a further 16.7%, shrinking
 * the too-small bitmap before the system scales it back up.
 *
 * Rather than generate bigger PNGs, this writes what the layers should have
 * been: a colour for the background, which cannot blur at any size, and a
 * vector drawable for the mark, which is sharp at every density including ones
 * that do not exist yet.
 *
 * Runs after `capacitor-assets` (see the `icons` script) because android/ is
 * gitignored — the generated tree does not survive a fresh clone or
 * `npx cap add android`, so the fix has to be re-applied rather than committed.
 */
import { mkdir, rm, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';

const INK = '#241C13';
const CREAM = '#F3E9DC';
const TERRACOTTA = '#E1623C';

const RES = join(process.cwd(), 'android/app/src/main/res');

/**
 * The mark from assets/coachlink-icon.svg, as Android path data.
 *
 * Coordinates have the master's translate(-1.75 -8.75) baked in, and the
 * viewport stays 220 so the two stay comparable. Circles become the standard
 * two-arc path because a vector drawable has no <circle>. Draw order matches
 * the SVG: the ring and its stem go under the whistle body.
 */
const FOREGROUND = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/android-adaptive-icon.mjs — edit assets/coachlink-icon.svg instead. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="220"
    android:viewportHeight="220">
    <!-- Whistle ring -->
    <path
        android:pathData="M45.25,75.25 a11,11 0 1,0 22,0 a11,11 0 1,0 -22,0"
        android:strokeColor="${CREAM}"
        android:strokeWidth="7" />
    <!-- Stem, tucked under the body below -->
    <path
        android:pathData="M64.25,83.25 L76.25,95.25"
        android:strokeColor="${CREAM}"
        android:strokeWidth="7"
        android:strokeLineCap="round" />
    <!-- Mouthpiece -->
    <path
        android:pathData="M103.25,71.25 h66 a9,9 0 0 1 9,9 v18 a9,9 0 0 1 -9,9 h-66 a9,9 0 0 1 -9,-9 v-18 a9,9 0 0 1 9,-9 z"
        android:fillColor="${TERRACOTTA}" />
    <!-- Body -->
    <path
        android:pathData="M52.25,115.25 a44,44 0 1,0 88,0 a44,44 0 1,0 -88,0"
        android:fillColor="${TERRACOTTA}" />
    <!-- Air hole, matching the background layer -->
    <path
        android:pathData="M81.25,115.25 a15,15 0 1,0 30,0 a15,15 0 1,0 -30,0"
        android:fillColor="${INK}" />
</vector>
`;

const COLORS = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/android-adaptive-icon.mjs -->
<resources>
    <color name="ic_launcher_background">${INK}</color>
</resources>
`;

/**
 * A 6% inset, which is neither of the obvious answers.
 *
 * The mark's furthest point from centre — the mouthpiece's top-right corner —
 * sits at 38.5dp on a 108dp canvas. A circular launcher mask only guarantees
 * the central 72dp circle, so at full bleed that corner is about 2.5dp outside
 * what is safe and a round launcher would shave it. 6% scales the layer to
 * 95dp, putting the corner at 33.9dp with room to spare.
 *
 * capacitor-assets used 16.7%, the maximum, which is the safe answer for
 * artwork nobody has measured: it renders the mark at roughly 45dp. This puts
 * it at 59dp — a third larger, and still inside the mask.
 */
const adaptive = (name) => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/android-adaptive-icon.mjs -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground>
        <inset android:drawable="@drawable/${name}" android:inset="6%" />
    </foreground>
</adaptive-icon>
`;

const DENSITIES = ['ldpi', 'mdpi', 'hdpi', 'xhdpi', 'xxhdpi', 'xxxhdpi'];

async function write(relative, contents) {
  const path = join(RES, relative);
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, contents, 'utf8');
  return relative;
}

async function main() {
  const written = [
    await write('drawable/ic_launcher_foreground.xml', FOREGROUND),
    await write('values/ic_launcher_background.xml', COLORS),
    await write('mipmap-anydpi-v26/ic_launcher.xml', adaptive('ic_launcher_foreground')),
    await write('mipmap-anydpi-v26/ic_launcher_round.xml', adaptive('ic_launcher_foreground')),
  ];

  // The PNG layers are now unreferenced — only the adaptive XML used them, and
  // a vector drawable cannot live in mipmap/. Leaving them would ship six
  // copies of a colour swatch and six of a blurry mark in every APK.
  // ic_launcher.png and ic_launcher_round.png stay: they are the pre-API-26
  // fallback, at the legacy sizes that are correct for it.
  let removed = 0;
  for (const density of DENSITIES) {
    for (const layer of ['foreground', 'background']) {
      const path = join(RES, `mipmap-${density}/ic_launcher_${layer}.png`);
      try {
        await rm(path);
        removed += 1;
      } catch {
        // Not there — capacitor-assets skips densities it has no source for.
      }
    }
  }

  console.log(`Android adaptive icon: wrote ${written.length} files, removed ${removed} bitmap layers.`);
  for (const file of written) console.log(`  ${file}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
